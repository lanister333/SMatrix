/**
 * Проверка конкретности товара (ТЗ п.2/3).
 * Вопрос считается слишком общим, если в заголовке и тексте нет НИ ОДНОГО
 * признака конкретики (латинских букв или цифр — обычно это модель/артикул/
 * размер), но при этом встречается слово-категория товара или общий вопрос
 * о дешёвых магазинах/категориях. Вопросы с моделью, артикулом, размером
 * («Bosch S5 AGM 70 Ah», «205/55 R16») проходят проверку всегда.
 */
export function isTooGeneric(title: string, text: string): boolean {
  const combined = `${title}\n${text}`;
  // Признак конкретики: латиница (модель/бренд) или цифры (артикул/размер/объём).
  if (/[a-z]/i.test(combined) || /\d/.test(combined)) return false;
  const s = combined.toLowerCase();
  return GENERIC_GOODS.some((w) => s.includes(w)) || GENERIC_SHOP.some((w) => s.includes(w));
}

/**
 * Защита от смешивания нескольких товаров в одной публикации (ТЗ п.3/4).
 * Проверяем ТОЛЬКО заголовок: перечисление товаров пользователь почти всегда
 * пишет в нём (пример ТЗ: «Где дешевле купить Bosch S5, телевизор Samsung
 * и шины Nokian?»). Заголовок делится на сегменты по запятым и союзам
 * «и/или» (союз нормализуем отдельно — \b в JS не работает с кириллицей);
 * сегмент «товарный», если в нём ≥2 латинских слова ≥3 знаков (бренд + модель)
 * или слово-категория товара. Два товарных сегмента с РАЗНЫМИ брендами =
 * несколько товаров в вопросе. Повтор бренда одного товара — не нарушение.
 */
export function isMultipleProducts(title: string, _text: string): boolean {
  const normalized = title.replace(/(?:^|\s)(?:и|или)(?:\s|$)/gi, ",");
  const segments = normalized
    .split(/[,;]/)
    .map((s) => s.trim())
    .filter((s) => s.length > 1);
  const brandSets: Set<string>[] = [];
  for (const seg of segments) {
    const lower = seg.toLowerCase();
    const brands = (seg.match(/\b[a-z][a-z0-9]{2,}\b/gi) ?? []).map((w) => w.toLowerCase());
    const isBearing = new Set(brands).size >= 2 || GENERIC_GOODS.some((w) => lower.includes(w));
    if (!isBearing) continue;
    brandSets.push(new Set(brands));
  }
  if (brandSets.length < 2) return false;
  for (let i = 0; i < brandSets.length; i++) {
    for (let j = i + 1; j < brandSets.length; j++) {
      const a = brandSets[i];
      const b = brandSets[j];
      let common = 0;
      for (const w of a) if (b.has(w)) common++;
      // Разные товары: бренды не пересекаются, либо каждый сегмент
      // содержит бренд, которого нет в другом (разные модели одного бренда).
      const aSubsetOfB = [...a].every((w) => b.has(w));
      const bSubsetOfA = [...b].every((w) => a.has(w));
      if (common === 0 || (!aSubsetOfB && !bSubsetOfA)) return true;
    }
  }
  return false;
}

