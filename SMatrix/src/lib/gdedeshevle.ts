/** Набор значимых токенов вопроса (для сравнения похожести). */
export function significantTokens(s: string): Set<string> {
  const raw = s.toLowerCase().match(/[a-zа-яё0-9][a-zа-яё0-9-]*/g) ?? [];
  const out = new Set<string>();
  for (let w of raw) {
    w = w.replace(/^[-]+|[-]+$/g, "");
    if (w.length < 2 || STOPWORDS.has(w)) continue;
    if (/[а-яё]/.test(w) && w.length >= 6) {
      for (const suf of SUFFIXES) {
        if (w.length - suf.length >= 4 && w.endsWith(suf)) {
          w = w.slice(0, w.length - suf.length);
          break;
        }
      }
    }
    if (w.length >= 2) out.add(w);
  }
  return out;
}

/**
 * Похожи ли два вопроса: общие значимые слова. Достаточно одного длинного
 * общего слова (модель/товар, ≥5 знаков) или двух общих слов.
 */
export function questionsSimilar(a: Set<string>, b: Set<string>): boolean {
  let shared = 0;
  let strong = 0;
  for (const t of a) {
    if (!b.has(t)) continue;
    shared++;
    if (t.length >= 5) strong++;
  }
  if (strong >= 1 && shared >= 1) return true;
  if (shared >= 2) return true;
  return false;
}

/** Нормализация заголовка для защиты от повторной публикации одного и того же (ТЗ п.31.14). */
export function normalizedTitle(title: string): string {
  return title.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, " ").trim();
}
