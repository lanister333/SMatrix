/**
 * Шаг 10: тег «Дороги» для блока «Оперативная обстановка на перевалах»
 * на /weather.php.
 *
 * ТЗ: в самом низу страницы — лог из 3 последних текстовых сообщений
 * из базы данных, которые публикуются пользователями с тегом или в
 * категории «Дороги». Отдельного тега/рубрики «Дороги» в схеме БД нет,
 * поэтому тег выводится той же внутренней логикой, что районы
 * отключений (Шаг №7.5, src/lib/outages-taxonomy.ts): сообщение
 * относится к категории «Дороги», если его текст про дороги,
 * перевалы, трассы, пробки/заслоны, гололёд, ямы и объезды.
 *
 * Задача фильтра двойная:
 *  1) отсечь болтовню в дорожных темах («Согласен.», «Актуально,
 *     следим.», «Поддерживаю вопрос.») — в лог попадают только
 *     содержательные отчёты;
 *  2) не ловить ложные срабатывания слова «дорог»: «но дорого»,
 *     «подорожал» — это не про дороги (поэтому в шаблоне стоят
 *     осторожные окончания: дорог[аеуи], дорожн).
 *
 * Модуль чистый (без node-зависимостей) — покрывается юнит-тестами
 * scripts/test-informers.ts (секция Шага 10).
 */

const ROAD_RE =
  /перевал|трасс|64\s*н|голол[её]д|занос|заслон|пробк|развязк|взл[её]тк|объезжа|объеха|перекры|дорожн|дорог[аеуи]|яма[ ,.;:!?)]|отбойник|барьер/i;

/** Сообщение относится к категории «Дороги»? */
export function isRoadReport(body: string): boolean {
  if (!body) return false;
  return ROAD_RE.test(body);
}

/** Одна запись лога «Обстановка на перевалах» (ответ /api/weather/roads). */
export interface RoadReportItem {
  id: string;
  author: string;
  body: string;
  createdAt: string;
  topic: number;
}

/** Ответ /api/weather/roads. */
export interface RoadsData {
  source: "db" | "none";
  items: RoadReportItem[];
  updated: string;
}
