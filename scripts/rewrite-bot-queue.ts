// Фразы-обёртки для сленга — сленг вставляется в [СЛЕНГ]
const SLANG_WRAPPERS = [
  "А то у нас [СЛЕНГ] сплошной.",
  "Хотя у нас на острове [СЛЕНГ] — обычное дело.",
  "Ну, [СЛЕНГ], в общем.",
  "Хотя, как говорится, [СЛЕНГ].",
  "У нас тут [СЛЕНГ] постоянно.",
];

function pickRandom<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

function detectCategory(text: string): TopicCategory {
  const lower = text.toLowerCase();
  for (const cat of CATEGORIES) {
    if (cat.id === "general") continue;
    for (const kw of cat.keywords) {
      if (lower.includes(kw)) return cat;
    }
  }
  return CATEGORIES[CATEGORIES.length - 1];
}

/**
 * Сгенерировать ответ от лица бота.
 * Сленг применяется в 15% случаев (1 сленговое слово в дополнение к основному ответу).
 */
function generateBotReply(
  sourceText: string,
  botNickname: string,
  botGender: string | null,
  botBio: string | null
): string {
  const category = detectCategory(sourceText);

  let isLowercase = false;
  if (botBio) {
    try {
      const meta = JSON.parse(botBio);
      isLowercase = !!meta.is_lowercase;
    } catch {}
  }

  // Выбрать шаблоны по полу
  let pool: string[];
  if (botGender === "female") {
    pool = [...category.femaleReplies, ...category.commonReplies];
  } else {
    pool = [...category.maleReplies, ...category.commonReplies];
  }

  // Основной ответ
  let reply = pickRandom(pool);

  // 15% шанс — добавить сленговую фразу
  if (Math.random() < 0.15) {
    const slangWord = pickRandom(SLANG_WORDS);
    const wrapper = pickRandom(SLANG_WRAPPERS);
    const slangPhrase = wrapper.replace("[СЛЕНГ]", slangWord);
    reply = `${reply} ${slangPhrase}`;
  }

  // lowercase-стиль: убрать заглавные
  if (isLowercase) {
    reply = reply.toLowerCase();
    // Восстановить "я" — нет, в середине предложения "я" строчное, всё ок
  }

  // Иногда добавить упоминание автора темы
  const mentionMatch = sourceText.match(/@([^\s,]+)/);
  if (mentionMatch && Math.random() < 0.3) {
    reply = `@${mentionMatch[1]}, ${reply.charAt(0).toLowerCase()}${reply.slice(1)}`;
  }

  return reply.trim();
}

async function main() {
  const now = new Date();
  console.log(`[${now.toISOString()}] rewrite-bot-queue (template): starting`);

  const due = await db.botQueue.findMany({
    where: {
      status: "pending_rewrite",
      scheduledAt: { lte: now },
    },
    orderBy: { scheduledAt: "asc" },
    take: 20,
  });

  console.log(`  Found ${due.length} pending_rewrite items`);

  let rewritten = 0;
  let failed = 0;
  for (const item of due) {
    try {
      const bot = await db.user.findUnique({
        where: { id: item.botUserId },
        select: { nickname: true, gender: true, bio: true },
      });
      if (!bot) {
        await db.botQueue.update({
          where: { id: item.id },
          data: { status: "rejected", rejectReason: "Bot user not found" },
        });
        console.error(`  ❌ Bot not found: ${item.botUserId}`);
        failed++;
        continue;
      }

      const sourceText = item.sourceText || "";
      if (!sourceText) {
        await db.botQueue.update({
          where: { id: item.id },
          data: { status: "rejected", rejectReason: "Empty sourceText" },
        });
        failed++;
        continue;
      }

      const replyText = generateBotReply(sourceText, bot.nickname, bot.gender, bot.bio);
      console.log(`  ✓ ${bot.nickname} (topic ${item.topicId}): "${replyText.slice(0, 100)}"`);

      await db.botQueue.update({
        where: { id: item.id },
        data: {
          text: replyText,
          status: "approved",
        },
      });
      rewritten++;
    } catch (e) {
      console.error(`  ❌ Failed: ${item.id}:`, e instanceof Error ? e.message : e);
      failed++;
    }
  }
  console.log(`Done: rewritten=${rewritten}, failed=${failed}`);
}

main()
  .catch((e) => {
    console.error("Rewriter error:", e);
    process.exit(1);
  })
  .then(() => process.exit(0));
