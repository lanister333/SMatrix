/**
 * Юнит-прогон первой линии пре-модерации (ТЗ 2026-09-22).
 * Проверяет критерии заказчика на его же примерах + защита от ложных
 * срабатываний на легитимном негативе.
 */
import { premoderateReviewText } from "../src/lib/moderation/premoderation";

let fail = 0;
const ok = (name: string, cond: boolean, extra = "") => {
  if (!cond) fail++;
  console.log(`${cond ? "OK  " : "FAIL"} ${name}${extra ? " — " + extra : ""}`);
};
const run = (text: string) =>
  premoderateReviewText({ subject: "Тест", title: "Проверочный заголовок", text });

const HINT = "Пожалуйста, опишите конкретную ситуацию и ваш личный опыт без перехода на личности";

/* --- Примеры заказчика: РАЗРЕШЕНО (pass) --- */
ok("«Обвесили на 200 грамм»", run("Обвесили на 200 грамм!").verdict === "pass");
ok("«Икра пересолена»", run("Икра пересолена.").verdict === "pass");
ok("«Перенесли сроки доставки»", run("Перенесли сроки доставки на неделю.").verdict === "pass");
ok("«Не рекомендую»", run("Больше сюда не приду, не рекомендую.").verdict === "pass");
ok("«Возможно, сломался холодильник»", run("Морозилка не морозит. Возможно, сломался холодильник.").verdict === "pass");
ok("фактурный негатив с датой/ценой", run("10 сентября купил икру за 3500 рублей. Пересолена, обвес 200 грамм. Не рекомендую.").verdict === "pass");

/* --- П.1 Ярлыки → return + точная подсказка --- */
for (const t of ["Там работают дебилы", "Директор — вор", "Контора мошенников"]) {
  const v = run(t);
  ok(`ярлык: «${t}» → return/insults`, v.verdict === "return" && v.rule === "insults", JSON.stringify(v));
}
ok("подсказка 1-в-1", run("Там работают дебилы").message === HINT, run("Там работают дебилы").message);
ok("составной ярлык-текст", run("Директор — вор, контора мошенников. Обвесили на 200 грамм!").rule === "insults");
ok("«неадекватные цены» — НЕ ярлык (pass)", run("Цены неадекватные, кофе 500 рублей.").verdict === "pass");
ok("«работают неадекваты» — ярлык", run("Работают неадекваты.").rule === "insults");
ok("«психолог» не задет", run("Посоветовали хорошего психолога, рекомендую.").verdict === "pass");
ok("«психотерапевт» не задет", run("Записалась к психотерапевту — помогло.").verdict === "pass");
ok("«психи» — ярлык", run("Там одни психи.").rule === "insults");
ok("«ворота» не задет", run("Красивые ворота у магазина, ул. Пуркаева.").verdict === "pass");
ok("«махнули» не ярлык", run("Махнули рукой на жалобу.").verdict === "pass");
ok("«нахамили» — поведение, не ярлык (pass)", run("Продавец нахамил, но вопрос решили.").verdict === "pass");
ok("«нашла крысу» — ФАКТ, не ярлык (pass)", run("Увидела крысу в торговом зале. Не рекомендую.").verdict === "pass");
ok("«обманули» — факт (pass)", run("Обманули со сроками: обещали 3 дня, ждал месяц.").verdict === "pass");

/* --- П.2 Личные данные → return --- */
ok("номер сотового", (() => {
  const v = run("Курьер rud. Его номер +7 914 123-45-67, заберите посылку.");
  return v.verdict === "return" && v.rule === "personal_data";
})());
ok("номер без +7", (() => {
  const v = run("Телефон сотрудника 89141234567.");
  return v.rule === "personal_data";
})());
ok("домашний адрес", (() => {
  const v = run("Курьер rud, проживает по адресу ул. Ленина, 25, кв. 7.");
  return v.rule === "personal_data";
})());
ok("«прописана по адресу»", (() => {
  const v = run("Менеджер прописана по адресу Холмск, ул. Советская, 1.");
  return v.rule === "personal_data";
})());
ok("«адрес курьера»", (() => {
  const v = run("Пишу адрес курьера: Южно-Сахалинск, д. 5.");
  return v.rule === "personal_data";
})());
ok("бизнес-адрес НЕ флаг (pass)", run("Магазин находится по адресу ул. Пуркаева, 15. Обвесили на 200 грамм.").verdict === "pass");
ok("горячая линия 8-800 НЕ флаг (pass)", run("Звонил на горячую линию 8-800-555-35-35, без ответа.").verdict === "pass");
ok("цены «8 000 рублей» НЕ флаг (pass)", run("Смета вышла 8 000 рублей за выезд. Дорого.").verdict === "pass");
ok("даты НЕ флаг (pass)", run("18.09.2026 взял заказ, привезли только 20 числа.").verdict === "pass");

/* --- П.3 БЛОК: угрозы / мат / капслок --- */
ok("угроза «набью лицо»", (() => {
  const v = run("Приеду и набью ему лицо, мокрое место оставлю.");
  return v.verdict === "block" && v.rule === "threats";
})());
ok("угроза «убью»", (() => {
  const v = run("Убью этого директора.");
  return v.rule === "threats";
})());
ok("угроза «сломаю руки»", (() => {
  const v = run("Сломаю тебе руки.");
  return v.rule === "threats";
})());
ok("угроза «сломают ноги» (3-е лицо)", (() => {
  const v = run("Сломают ноги за такое отношение.");
  return v.rule === "threats";
})());
ok("прошедшее «избили» — не угроза, но ярлык-проверка", (() => {
  const v = run("Охранник избил покупателя при мне, писал заявление.");
  return v.verdict === "pass" || v.rule !== "threats";
})());
ok("мат → block/profanity", (() => {
  const v = run("Поставили какую-то хуйню вместо детали, всё развалилось.");
  return v.verdict === "block" && v.rule === "profanity";
})());
ok("капслок → block/capslock", (() => {
  const v = run("ОБВЕШАЮТ КАЖДЫЙ РАЗ ОБСЛУЖИВАНИЕ УЖАСНОЕ ЖДАЛИ ПОЧТИ ЧАС");
  return v.verdict === "block" && v.rule === "capslock";
})());
ok("капслок < порога (3 слова, pass)", run("ЖДАЛИ ЧАС ОБСЛУЖИВАНИЕ плохое.").verdict === "pass");
ok("аббревиатуры не капслок (pass)", run("ООО Ромашка, ЖКХ Починское и ИП Иванов обвешивают. ЖДАЛИ месяц ответа — не рекомендую.").verdict === "pass");

/* --- Порядок п.1 > п.2 > п.3 --- */
ok("ярлык + мат → insults (п.1 раньше)", (() => {
  const v = run("Дебилы тупые, что за хуйня.");
  return v.rule === "insults";
})());
ok("личные данные + ярлык → insults (п.1 раньше)", (() => {
  const v = run("Вор. Его номер 89141234567.");
  return v.rule === "insults";
})());
ok("личные данные + мат → personal_data (п.2 раньше)", (() => {
  const v = run("Телефон +7 914 123-45-67, что за хуйня служба.");
  return v.rule === "personal_data";
})());

/* --- Проверка всего текста публикации (subject/title/place/humanHighlight) --- */
ok("ярлык в subject", (() => {
  const v = premoderateReviewText({ subject: "Мошенники на Сахалинской", title: "Нормальный заголовок", text: "Опыт нормальный, но после правок." });
  return v.rule === "insults";
})());
ok("номер в humanHighlight", (() => {
  const v = premoderateReviewText({ subject: "Доставка", title: "Нормальный заголовок", text: "Курьер помог, но сначала спросил телефон.", humanHighlight: "Его номер +7 914 123-45-67" });
  return v.rule === "personal_data";
})());
ok("капслок в title", (() => {
  const v = premoderateReviewText({ subject: "Рыбный отдел", title: "ОБВЕШАЮТ КАЖДЫЙ РАЗ ОБСЛУЖИВАНИЕ", text: "Ждали почти час." });
  return v.rule === "capslock";
})());

console.log(fail === 0 ? "\nUNIT PREMOD: ALL OK" : `\nUNIT PREMOD: ${fail} FAIL`);
if (fail > 0) process.exit(1);
