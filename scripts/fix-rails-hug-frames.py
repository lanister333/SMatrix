#!/usr/bin/env python3
# Директива пользователя (Скриншот-20260919-121252.jpg): «бирюзовые вертикальные
# линии, которые висят и не доходят до какой-нибудь рамки, не нужны — удалить».
# Причина видимых «висящих» концов: колонки нитей стояли в 10–12px ЛЕВЕЕ рамок
# (x = 25·K − 13), поэтому концевые отрезки ветвей останавливались на ВЫСОТЕ
# нижней рамки последнего ответа, но В СТОРОНЕ от неё — визуально в воздухе.
# Фикс: нити прижимаются ВПЛОТНУЮ к левому краю рамок (колонка x = 25·K − 2,
# зазор 0), концы каждой нити ложатся точно на углы рамок:
#   - штырёк родителя: от его нижней рамки до верхнего левого угла ответа;
#   - низ ветви: на нижней рамке последнего ответа ветки;
#   - хвосты через зазор 8px сшивают нить со следующей карточкой ветки.
# Крючки «├» убраны (на эталоне autokochka их нет; прижатым нитям не нужны).
import sys

PATH = "/home/z/my-project/src/components/forum/topic-view.tsx"
src = open(PATH, encoding="utf-8").read()

def patch(old, new, note):
    global src
    n = src.count(old)
    if n != 1:
        print(f"FAIL [{note}]: count={n}"); sys.exit(1)
    src = src.replace(old, new)
    print(f"OK [{note}]")

# 1) Формула колонки: вплотную к рамкам
patch(
    "  const railLeft = (k: number, level: number) => (k - level) * 25 + 12;",
    "  const railLeft = (k: number, level: number) => (k - level + 1) * 25 - 3;",
    "railLeft formula",
)

# 2) Комментарий к формуле
patch(
    """  // Колонка нити K: 25·K − 13 в координатах контейнера (относительно
  // плашки уровня L: left = (K − L)·25 + 12px — ОТРИЦАТЕЛЬНОЕ, строго
  // левее рамки, в зазоре margin-left).""",
    """  // Колонка нити K: 25·K − 2 в координатах контейнера — ВПЛОТНУЮ к левому
  // краю рамок уровня K+1 (относительно плашки уровня L: left =
  // (K − L + 1)·25 − 3px). Директива «линии висят и не доходят до какой-
  // нибудь рамки — их надо удалить»: при старой колонке (25·K − 13) концы
  // нитей останавливались в 10px от рамок — висели в воздухе. Теперь конец
  // каждой нити лежит НА рамке: штырёк родителя упирается в верхний левый
  // угол ответа, низ ветви — в нижний левый угол последнего ответа.""",
    "railLeft comment",
)

# 3) Пункт 5 директивы: колонка и концы на рамках
patch(
    """  //    волны с образца), 2px, строго СНАРУЖИ рамок. Нить уровня K стоит на
  //    колонке x = 25·K − 13 (13px левее рамок уровня K+1). Директива""",
    """  //    волны с образца), 2px, ВПЛОТНУЮ к рамкам (снаружи, зазор 0). Нить
  //    уровня K стоит на колонке x = 25·K − 2 (вплотную к рамкам уровня
  //    K+1 — левый край нити касается рамки). Директива""",
    "directive item5 column",
)

# 4) Концы нитей — на рамках (добавка в пункт 5)
patch(
    """  //    (эталон autokochka.ru/forum/thread/1910375: концы нити только
  //    штырёк родителя и нижняя рамка последнего ответа ветки).""",
    """  //    (эталон autokochka.ru/forum/thread/1910375: концы нити только
  //    штырёк родителя и нижняя рамка последнего ответа ветки). ФИНАЛЬНОЕ
  //    ПРАВИЛО (директива от Скриншот-20260919-121252.jpg): КАЖДЫЙ конец
  //    нити обязан ЛЕЖАТЬ НА РАМКЕ — нить прижата к карточкам вплотную,
  //    поэтому верх ветви упирается в нижнюю рамку родителя (через штырёк),
  //    низ ветви — в нижнюю рамку последнего ответа. Ни один конец нити
  //    не остаётся в воздухе.""",
    "directive item5 ends",
)

# 5) Пункт 6: крючки убраны
patch(
    """  // 6) КРЮЧКИ и УГЛЫ по эталону autokochka.ru/forum/thread/1910375 (движок
  //    Сахкома, разметка tree-t/tree-l/tree-i): ответ висит на колонке СВОЕЙ
  //    ветки (K = L−1) горизонтальным отростком на высоте шапки — «├» (tree-t),
  //    если ветка ниже продолжается, и «└» (tree-l: вертикаль НЕ доходит до
  //    нижней рамки, а загибается в карточку), если ответ последний. Колонки
  //    предков (K < L−1) — сквозные «│» (tree-i) без крючков.""",
    """  // 6) БЕЗ КРЮЧКОВ (по эталону autokochka.ru/forum/thread/1910375: линии —
  //    чистые вертикали вплотную к карточкам, без горизонтальных отростков).
  //    Связь «нить → ответ» видна сама собой: нить прижата к левому краю
  //    рамки ответа, а штырёк родителя доводит её до верхнего угла карточки.""",
    "directive item6 no hooks",
)

# 6) Удаляем блок рендера крючков
patch(
    """                {(railsOf.get(m.id) ?? []).filter((r) => r.own).map(({ k }) => (
                  /* Крючок «├» (отметка ответа на колонке СВОЕЙ ветки): от колонки
                     до рамки карточки на высоте шапки. 22 = 21 (середина шапки) + 1
                     рамка. Сама вертикаль крючок НЕ обрывает: по директиве «линии
                     не висят и не доходят до конца — их не должно быть» она всегда
                     идёт от верхней рамки до нижней (эталон autokochka: нить ветки
                     заканчивается ТОЛЬКО на нижней рамке последнего ответа). */
                  <span key={`hook-${k}`} data-hook="1" className="sakh-comment-connector" style={{ left: railLeft(k, L), top: 21, width: 13, height: 2 }} aria-hidden="true" />
                ))}
""",
    "",
    "remove hooks block",
)

# 7) Комментарий штырька: угол-в-угол
patch(
    """                  /* Штырёк родителя: от его нижней рамки до верхней рамки
                     первого ответа — линия «ведёт к сообщению» */""",
    """                  /* Штырёк родителя: от его нижней рамки до верхнего ЛЕВОГО
                     УГЛА первого ответа (колонка вплотную к обеим рамкам) —
                     конец нити лежит на рамках, не висит в воздухе */""",
    "stub comment",
)

open(PATH, "w", encoding="utf-8").write(src)
print("saved")
