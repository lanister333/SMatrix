/**
 * Тест детерминированного фильтра нецензурной лексики (ШАГ 10).
 * Проверяет: обходы (символы, цифры, пробелы, повторы, латиница),
 * ложные срабатывания (обычные слова, подстроки), цитаты.
 */
import { checkProfanity } from "../src/lib/moderation/profanity";

const MUST_BLOCK = [
  // прямая лексика
  "мудак",
  "Какой же ты мудак!",
  "сука",
  "пошел на хуй",
  "блять",
  "идиот блядский",
  "гондон ты степной",
  // обходы: символы и пунктуация
  "м.у.д.а.к",
  "с,у,к,а",
  "муд@к",
  "х*й",
  "х..й",
  "х_у_й",
  // обходы: цифры
  "муд4к",
  "п3зд3ц",
  "г0вн0",
  "пизdец",
  // обходы: пробелы
  "с у ка",
  "м у д а к",
  "г о в н о",
  // обходы: повторы букв
  "сссууукааа",
  "пиииздееец",
  "муддааакк",
  // обходы: латиница
  "cyka",
  "xyй",
  "mudak",
  // намеренные искажения
  "мдак",
  "пздц",
  "хмло",
  // в цитатах
  "Прошу заметить: «ты мудак» — это цитата из прошлого ответа",
  "Он написал: с у ка!",
  // оскорбления
  "ты дебил",
  "чмо",
  "ты ч.м.о",
];

const MUST_PASS = [
  // обычные слова и ложные подстроки
  "Команда нашего города сделала отличный ремонт",
  "Мандат депутата продлили",
  "Мандарины с Сахалина очень вкусные",
  "Херсон — город на Днепре",
  "Даун-синдром не приговор, таким детям нужна помощь",
  "Мудрость приходит с возрастом",
  "Промедление смерти подобно",
  "Бляха муха, какая красота", // «бляха» — легитимное слово
  "Купил скотч для упаковки",
  "Скотный двор — отличная книга",
  "Урал — красивый край",
  "Гниение древесины можно остановить",
  "Сук дерева упал на дорогу",
  "Сучок немного торчит — отшлифуйте",
  "Поэт написал стихи о Сахалине",
  "Молоко подорожало",
  "Командировка в Южно-Сахалинск",
  // нейтральные сообщения с критикой (ЗАЩИТА МНЕНИЙ)
  "Считаю, что это решение вредное и вредно для города",
  "Дорога в ужасном состоянии, я недоволен",
  "Работа подрядчика выполнена плохо, требую переделки",
  "Не нравится, как обрабатывают заявки в УК",
];

let failed = 0;
for (const t of MUST_BLOCK) {
  const r = checkProfanity(t);
  if (!r.blocked) {
    failed++;
    console.log(`✗ НЕ ЗАБЛОКИРОВАНО: «${t}»`);
  }
}
for (const t of MUST_PASS) {
  const r = checkProfanity(t);
  if (r.blocked) {
    failed++;
    console.log(`✗ ЛОЖНОЕ СРАБАТЫВАНИЕ: «${t}» → ${JSON.stringify(r.hits)}`);
  }
}
console.log(failed === 0 ? "ВСЕ ТЕСТЫ ПРОШЛИ ✓" : `ПРОВАЛЕНО: ${failed}`);
process.exit(failed === 0 ? 0 : 1);
