#!/usr/bin/env python3
"""Пиксельный замер фона на скриншоте пользователя (upload/Скриншот-20260917-154009.jpg).
Цель: отличить новый фон #F4F6F7 (244,246,247) от старого белого (255,255,255).
JPEG вносит сдвиг +-2-3, но разница 244 vs 255 легко различима."""
from PIL import Image

img = Image.open("/home/z/my-project/upload/Скриншот-20260917-154009.jpg").convert("RGB")
W, H = img.size
print(f"размер: {W}x{H}")

def avg(x, y, r=3):
    """Средний цвет квадрата (2r+1)^2 вокруг точки."""
    px = []
    for dx in range(-r, r + 1):
        for dy in range(-r, r + 1):
            xx, yy = min(max(x + dx, 0), W - 1), min(max(y + dy, 0), H - 1)
            px.append(img.getpixel((xx, yy)))
    n = len(px)
    return tuple(round(sum(c[i] for c in px) / n) for i in range(3))

# Ориентиры на скриншоте (1568x844): центральная колонка x~977
points = {
    "зазор Подслушано<->Последние темы (центр. колонка)": (977, 372),
    "зазор ячейки Поддержка<->Нужна помощь": (600, 693),
    "поле слева от левой колонки (внешний фон)": (497, 600),
    "внутри белой карточки Подслушано (контроль)": (977, 345),
    "внутри белой карточки Навигация (контроль)": (600, 460),
    "шапка бирюзовая (контроль)": (700, 220),
}
print(f"{'точка':55} RGB")
for name, (x, y) in points.items():
    c = avg(x, y)
    print(f"{name:55} {c}")

# Вывод по контрольным точкам
gap1 = avg(977, 372)
card = avg(977, 345)
print("\nВЕРДИКТ:")
if abs(gap1[0] - 244) <= 4 and abs(gap1[0] - card[0]) >= 5:
    print("НОВЫЙ ФОН #F4F6F7 В ПРЕВЬЮ РАБОТАЕТ (зазор темнее карточки ~на 10 единиц)")
elif gap1[0] >= 252:
    print("СТАРАЯ СБОРКА: зазор белый (255) — нужен Publish")
else:
    print(f"промежуточный результат, зазор={gap1}, карточка={card} — смотреть вручную")
