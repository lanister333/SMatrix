// Санити-тест паттернов ТЗ 2026-09-21 (клиент 16 цифр + сервер 13/15/16/19)
const client = /\b(?:\d[ -]*?){16}\b/;
const server = [
  /\b(?:\d[ -]*?){13}\b/,
  /\b(?:\d[ -]*?){15}\b/,
  /\b(?:\d[ -]*?){16}\b/,
  /\b(?:\d[ -]*?){19}\b/,
];
const sTest = (t) => server.some((re) => re.test(t));

const blocked = [
  "4400111122223333", // 16 подряд
  "4400 1111 2222 3333", // 16 через пробелы
  "4400-1111-2222-3333", // 16 через дефисы
  "Переведите на карту 4111 1111 1111 1111 срочно", // 16 в тексте
  "4111111111111", // 13
  "378282246310005", // 15 (Amex)
  "6331101999990016801", // 19 (Maestro)
  "карта сбера 4276 5500 1420 1234, жду перевод", // в контактах
  "срок 2026-09-21, реквизиты 4400 1111 2222 3333", // рядом с датой
  "карта4400111122223333безразделителей", // впритык к кириллице
];
const allowed = [
  "Позвоните: +7 914 123 45 67", // 11 цифр телефона
  "8 (914) 753-89-12", // телефон с разделителями
  "Встреча 21 сентября 2026, после 18:00", // даты/время
  "заказ № 20260921 0930 на доставку", // 12 цифр
  "Почтовый индекс 693000, улица Пограничная", // 6 цифр
  "Привезу вещи бесплатно, помогу руками", // фразы-исключения
  "нужны автоволонтеры, пропал человек", // фразы-исключения
  "Telegram: @ivan_help", // без цифр
  "Скинь на чай 100 рублей", // мало цифр (ловит ИИ, не регулярка)
];

let fail = 0;
for (const t of blocked) {
  const c = client.test(t);
  const s = sTest(t);
  if (!s) { fail++; console.log(`FAIL(сервер пропустил): ${t}`); }
  else console.log(`OK блок  [клиент:${c ? "16-да" : "нет(пойдёт на сервер)"}] ${t}`);
}
for (const t of allowed) {
  if (client.test(t) || sTest(t)) { fail++; console.log(`FAIL(ложное срабатывание): ${t}`); }
  else console.log(`OK пропуск ${t}`);
}
console.log(fail === 0 ? "\nВСЕ ПРОВЕРКИ ПРОЙДЕНЫ" : `\nПРОВАЛОВ: ${fail}`);
process.exit(fail === 0 ? 0 : 1);
