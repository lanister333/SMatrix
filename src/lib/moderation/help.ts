/**
 * ШАГ 16. Модерация раздела «Нужна помощь» — самостоятельной доски
 * просьб о безвозмездной помощи.
 *
 * Принципы (по ТЗ):
 *  — проверяются мошенничество, скрытые платные услуги, коммерческая реклама,
 *    сбор денег, вакансии/поиск работников, продажа/покупка, чужие
 *    персональные данные, спам и запрещённый контент;
 *  — ОБЫЧНАЯ просьба о безвозмездной помощи НЕ должна ошибочно
 *    блокироваться только из-за содержания самой просьбы;
 *  — расходы (бензин, материалы и т.п.) допустимы, если они прямо и
 *    понятно указаны в тексте объявления;
 *  — благодарность («спасибо», «угощу кофе/пирогами») — не нарушение;
 *  — спорные случаи передаются человеку-модератору.
 */

import { aiModerate, type ModerationOutcome } from "./index";
import { checkProfanity } from "./profanity";

/** Причины жалоб в разделе «Нужна помощь» (по ТЗ). */
export const HELP_COMPLAINT_CATEGORIES = [
  "fraud", // Мошенничество
  "paid", // Скрытая платная услуга
  "ad", // Реклама
  "spam", // Спам
  "personal_data", // Чужие персональные данные
  "forbidden", // Запрещённый контент
  "other", // Другое нарушение
] as const;

/** Маппинг категорий раздела на категории лестницы санкций форума. */
const SANCTION_CATEGORY_MAP: Record<string, string> = {
  fraud: "fraud",
  paid: "spam",
  ad: "spam",
  job: "spam",
  sale: "spam",
  spam: "spam",
  personal_data: "personal_data",
  forbidden: "forbidden",
  profanity: "insult",
  other: "other",
};

export function helpSanctionCategory(category: string | undefined): string {
  return SANCTION_CATEGORY_MAP[category ?? "other"] ?? "other";
}

/* ТЗ 2026-09-21: серверный ИИ-модератор раздела взаимопомощи — жёсткое
 * пресечение сбора денежных средств, публикации платёжных реквизитов и
 * мошенничества. Текст серверной ошибки валидации — из ТЗ 1-в-1. */
export const HELP_MONEY_BLOCK_MESSAGE =
  "Ошибка модерации: Обнаружены запрещенные платежные реквизиты или призывы к сбору денежных средств. Раздел функционирует только на безвозмездной основе.";

/**
 * Правило 1 серверного ИИ-модератора (ТЗ 2026-09-21): номер банковской карты
 * 16 цифр, а также 13/15/19-значный; цифры могут быть разделены пробелами и
 * дефисами. Детерминированный серверный фильтр дополняет клиентский (16 цифр,
 * сниппет на форме) и ИИ-модератора (маскировка словами — правило 2).
 * \b в JS — по ASCII-\w, граница с кириллицей распознаётся корректно.
 */
const HELP_CARD_PATTERNS = [
  /\b(?:\d[ -]*?){13}\b/, // 13 цифр
  /\b(?:\d[ -]*?){15}\b/, // 15 цифр
  /\b(?:\d[ -]*?){16}\b/, // 16 цифр (клиентский паттерн ТЗ)
  /\b(?:\d[ -]*?){19}\b/, // 19 цифр
];

function containsCardNumber(text: string): boolean {
  return HELP_CARD_PATTERNS.some((re) => re.test(text));
}

/**
 * Системный промпт серверного ИИ-модератора. ТЗ 2026-09-21 («ВЫ — СЕРВЕРНЫЙ
 * ИИ-МОДЕРАТОР SAKHMATRIX.RU (РАЗДЕЛ ВЗАИМОПОМОЩИ)») включён 1-в-1: основная
 * задача, правила анализа текста 1–3, допустимые исключения. Адаптации
 * (задокументированы): (1) сохранён JSON-контракт ответа verdict/category/
 * reason/note — на нём построен разбор в aiModerateHelp; (2) нарушение правил
 * 1–3 помечается verdict "violation" + категория "fraud" — конвейер в этом
 * случае возвращает серверную ошибку валидации с текстом из ТЗ
 * (HELP_MONEY_BLOCK_MESSAGE); (3) прочие ОЧЕВИДНЫЕ нарушения раздела
 * (по прежнему ТЗ ШАГ 16) сохранены — ТЗ про реквизиты их не отменяет;
 * (4) фразы-исключения помечены как признак безвозмездной помощи, чтобы они
 * не проваливались в «спорный случай».
 */
const HELP_SYSTEM_PROMPT = `Ты — СЕРВЕРНЫЙ ИИ-МОДЕРАТОР SAKHMATRIX.RU (РАЗДЕЛ ВЗАИМОПОМОЩИ). Это простая городская доска объявлений с просьбами о БЕЗВОЗМЕЗДНОЙ помощи: текст просьбы + контактные данные + статус. Никаких обсуждений.

ОСНОВНАЯ ЗАДАЧА:
Жестко пресекать любые попытки сбора денежных средств, публикацию платежных реквизитов и мошенничество.

ПРАВИЛА АНАЛИЗА ТЕКСТА (проверяются Заголовок, Описание и Контакты):
1. Если в тексте заявки (Заголовок, Описание или Контакты) обнаружен 16-значный (или 13, 15, 19-значный) номер банковской карты — НЕ ДОПУСКАТЬ ПУБЛИКАЦИЮ.
2. Если автор пытается замаскировать номер карты словами (например, «четыре четыре ноль ноль...», «карта сбера четыре один...») или использует спецсимволы между цифрами — НЕ ДОПУСКАТЬ ПУБЛИКАЦИЮ.
3. Если автор прямо просит перевести деньги, скинуть на лечение, на билет, на продукты — НЕ ДОПУСКАТЬ ПУБЛИКАЦИЮ.

При нарушении правил 1–3 ставь вердикт "violation" с категорией "fraud" — раздел вернёт автору серверную ошибку валидации: «Ошибка модерации: Обнаружены запрещенные платежные реквизиты или призывы к сбору денежных средств. Раздел функционирует только на безвозмездной основе.» Признаки сбора денег и мошенничества: просьбы перевести деньги на карту/кошелёк/телефон, «сбор средств», предоплаты, фишинг, «заработок», финансовые пирамиды, розыгрыши с переводом денег, платёжные реквизиты в любом виде.

ДОПУСТИМЫЕ ИСКЛЮЧЕНИЯ (одобрять автоматически):
Если в тексте упоминаются фразы «бесплатно», «привезу вещи», «помогу руками», «нужны автоволонтеры», «пропал человек» — одобрять публикацию автоматически (verdict: "ok"). Эти фразы — признак безвозмездной помощи: сами по себе они НЕ нарушение и НЕ повод для спорного случая.

Помечай как НАРУШЕНИЕ (verdict: "violation") также прочие ОЧЕВИДНЫЕ случаи:
1. Скрытая платная услуга — под видом просьбы о помощи на самом деле предлагают платную услугу или просят оплату («напишите — расскажу условия», «помогу за деньги», указаны цены для оплаты помощи).
2. Коммерческая реклама — реклама бизнеса, магазинов, брендов, ссылок на продажу, массовые повторяющиеся рекламные тексты.
3. Вакансии / поиск работников / предложения заработка — найм, «требуются», «ищу сотрудников», «предлагаю подработку».
4. Продажа / покупка товаров — «продаю», «куплю», «отдам за деньги».
5. Чужие персональные данные — чужие телефоны, адреса, ФИО без согласия человека, доксинг.
6. Запрещённый контент — призывы к насилию, наркотики, порнография, разжигание ненависти, экстремизм, крайне опасные советы.
7. Нецензурная и оскорбительная лексика — мат, оскорбления людей.
8. Спам — бессмысленные повторяющиеся объявления.

ВАЖНО — НЕ БЛОКИРУЙ обычные просьбы о помощи. РАЗРЕШЕНО:
- Любая обычная просьба о безвозмездной помощи, например: помочь пожилому человеку, помочь с бытовой ситуацией, помочь найти потерянную вещь, помочь разобраться в вопросе, помочь физически или информационно, попросить совета или содействия; а также перевезти вещи, помочь с ремонтом, донести мебель, выкопать огород, посидеть с ребёнком, помочь с документами, найти кота и т.п.
- Упоминание расходов, если они ПРЯМО И ПОНЯТНО указаны в тексте («оплачу бензин», «расходы на материалы за мой счёт», «возмещу билеты») — это НЕ нарушение.
- Благодарность и символические жесты («спасибо», «угощу пирогами», «накормлю обедом», «отблагодарю») — это НЕ нарушение и НЕ скрытая оплата.
- Просьбы с контактами в виде телефона, Telegram, WhatsApp — это нормально, автор сам указывает способ связи (а может и не указывать контакт).

ЕСЛИ СОМНЕВАЕШЬСЯ: непонятно, помощь или услуга; благодарность или скрытая оплата; настоящие данные или вымышленные — это СПОРНЫЙ случай (verdict: "ambiguous"), его рассмотрит человек-модератор. Лучше передать человеку, чем ошибочно заблокировать просьбу о помощи.

Ответь СТРОГО валидным JSON без пояснений:
{"verdict":"ok|violation|ambiguous","category":"fraud|paid|ad|job|sale|spam|personal_data|forbidden|profanity|other","reason":"краткая причина на русском (для violation, иначе пусто)","note":"краткая заметка модератора на русском (до 100 символов)"}`;

export interface HelpAiVerdict {
  verdict: "ok" | "violation" | "ambiguous";
  category: string;
  reason: string;
  note: string;
}

const HELP_VALID_CATEGORIES = new Set([
  "fraud", "paid", "ad", "job", "sale", "spam", "personal_data", "forbidden", "profanity", "other",
]);

/** ИИ-вердикт по тексту публикации «Нужна помощь». Бросает исключение при недоступности ИИ.
 * ТЗ 2026-09-21 (правило 1): анализируются Заголовок, Описание И Контакты —
 * поэтому contactData включён в проверяемый текст (раньше ИИ видел только
 * заголовок и текст). */
export async function aiModerateHelp(title: string, text: string, contactData?: string): Promise<HelpAiVerdict> {
  // Переиспользуем общий механизм вызова ИИ: aiModerate применяет форумный промпт,
  // поэтому для раздела нужен собственный вызов с тем же SDK и таймаутом.
  const ZAI = (await import("z-ai-web-dev-sdk")).default;
  const zai = await ZAI.create();
  const completion = await Promise.race([
    zai.chat.completions.create({
      messages: [
        { role: "system", content: HELP_SYSTEM_PROMPT },
        {
          role: "user",
          content: `Проверь публикацию раздела «Нужна помощь» (заголовок, текст, контакты):\n\nЗАГОЛОВОК:\n"""\n${title.slice(0, 300)}\n"""\n\nТЕКСТ:\n"""\n${text.slice(0, 6000)}\n"""\n\nКОНТАКТЫ:\n"""\n${(contactData ?? "").slice(0, 300)}\n"""`,
        },
      ],
      thinking: { type: "disabled" },
    }),
    new Promise<never>((_, reject) => setTimeout(() => reject(new Error("AI timeout")), 45000)),
  ]);

  const { extractJson } = await import("./ai");
  const content = completion.choices[0]?.message?.content ?? "";
  const parsed = extractJson(content);
  if (!parsed) throw new Error("AI: не удалось разобрать ответ");

  const rawVerdict = String(parsed.verdict ?? "").toLowerCase();
  const verdict = rawVerdict === "violation" ? "violation" : rawVerdict === "ambiguous" ? "ambiguous" : "ok";
  let category = String(parsed.category ?? "other").toLowerCase();
  if (!HELP_VALID_CATEGORIES.has(category)) category = "other";

  let reason = String(parsed.reason ?? "").trim();
  if (verdict === "violation" && !reason) reason = "нарушение правил раздела «Нужна помощь»";

  let note = String(parsed.note ?? "").trim().slice(0, 200);
  if (!note) {
    note =
      verdict === "violation"
        ? `нарушение: ${reason}`
        : verdict === "ambiguous"
          ? "спорный случай — передано человеку-модератору"
          : "нарушений не найдено";
  }

  return { verdict, category, reason, note };
}

/** Полный текст публикации для проверки лексики. */
function helpFullText(title: string, text: string, contactData?: string): string {
  return [title, text, contactData ?? ""].filter(Boolean).join("\n");
}

/**
 * Проверка НОВОГО объявления перед публикацией (и при редактировании).
 * Шаг 1 — детерминированный фильтр лексики; шаг 1.5 — детерминированный
 * фильтр платёжных реквизитов (ТЗ 2026-09-21); шаг 2 — ИИ раздела помощи.
 */
export async function moderateNewHelpText(
  title: string,
  text: string,
  contactData?: string
): Promise<ModerationOutcome & { helpCategory?: string }> {
  // Шаг 1. Общий фильтр нецензурной/оскорбительной лексики (общий механизм сайта).
  const prof = checkProfanity(helpFullText(title, text, contactData));
  if (prof.blocked) {
    return {
      action: "block",
      blockMessage:
        "Сообщение содержит нецензурную или оскорбительную лексику. Пожалуйста, отредактируйте текст и попробуйте снова.",
      aiNote: "нецензурная лексика (автофильтр)",
      needHuman: false,
      source: "profanity",
      hits: prof.hits,
      helpCategory: "profanity",
    };
  }

  // Шаг 1.5. ТЗ 2026-09-21, правило 1 серверного ИИ-модератора: номер карты
  // 13/15/16/19 цифр (в т.ч. разделённый пробелами/дефисами) — НЕ ДОПУСКАТЬ
  // ПУБЛИКАЦИЮ: серверная ошибка валидации с текстом из ТЗ (1-в-1).
  // Охватывает и создание, и редактирование (оба пути идут через эту функцию).
  if (containsCardNumber(helpFullText(title, text, contactData))) {
    return {
      action: "block",
      blockMessage: HELP_MONEY_BLOCK_MESSAGE,
      aiNote: "платёжные реквизиты — номер банковской карты (автофильтр)",
      needHuman: false,
      source: "card-filter",
      helpCategory: "fraud",
    };
  }

  // Шаг 2. ИИ-модератор раздела (маскировка реквизитов словами — правило 2,
  // прямые просьбы перевести деньги — правило 3).
  try {
    const ai = await aiModerateHelp(title, text, contactData);
    if (ai.verdict === "violation") {
      // ТЗ 2026-09-21: сбор денег/реквизиты/мошенничество (категория fraud) —
      // серверная ошибка валидации, публикация не создаётся вовсе (ДЕЙСТВИЕ
      // ПРИ НАРУШЕНИИ из ТЗ). Дельта от прежнего поведения (hide + санкции)
      // задокументирована в worklog; прочие категории — прежний конвейер.
      if (ai.category === "fraud") {
        return {
          action: "block",
          blockMessage: HELP_MONEY_BLOCK_MESSAGE,
          aiNote: ai.note,
          needHuman: false,
          source: "ai",
          helpCategory: "fraud",
        };
      }
      return {
        action: "hide",
        hiddenReason: ai.reason,
        aiNote: ai.note,
        needHuman: false,
        source: "ai",
        category: helpSanctionCategory(ai.category),
        helpCategory: ai.category,
      };
    }
    if (ai.verdict === "ambiguous") {
      return {
        action: "human",
        aiNote: ai.note,
        needHuman: true,
        source: "ai",
        category: helpSanctionCategory(ai.category),
        helpCategory: ai.category,
      };
    }
    return { action: "allow", aiNote: ai.note, needHuman: false, source: "ai", helpCategory: ai.category };
  } catch {
    // ИИ недоступен: лексический фильтр пройден — публикуем,
    // но обязательно ставим в очередь человеку-модератору.
    return {
      action: "human",
      aiNote: "ИИ-модератор недоступен — требуется проверка человеком",
      needHuman: true,
      source: "fallback",
    };
  }
}

/** Повторная проверка УЖЕ опубликованной публикации (по жалобе). */
export async function moderatePublishedHelpText(
  title: string,
  text: string,
  contactData?: string
): Promise<ModerationOutcome & { helpCategory?: string }> {
  const outcome = await moderateNewHelpText(title, text, contactData);
  if (outcome.action === "block") {
    return {
      ...outcome,
      action: "hide",
      // Причина по факту блокировки: блоком теперь может быть не только
      // лексика, но и платёжные реквизиты/сбор денег (ТЗ 2026-09-21).
      hiddenReason:
        outcome.helpCategory === "fraud"
          ? "платёжные реквизиты или призыв к сбору денежных средств"
          : "нецензурная или оскорбительная лексика",
      needHuman: false,
    };
  }
  return outcome;
}
