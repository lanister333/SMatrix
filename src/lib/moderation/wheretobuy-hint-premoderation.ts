import { findPhoneNumbers } from "./premoderation";

export type HintPremodVerdictKind = "pass" | "block";
/** Кейс А — телефоны, Кейс Б — эмоциональные ярлыки (нумерация заказчика). */
export type HintPremodRule = "phones" | "labels";

export interface HintPremodVerdict {
  /** pass — пропуск на главную; block — блокировка с плашкой перенаправления. */
  verdict: HintPremodVerdictKind;
  rule: HintPremodRule | null;
  /** Сработавшие фрагменты (для логов/заметки модератора). */
  hits: string[];
  /** Текст строгой плашки Flat 2.0 (дословно заказчик). Для pass — пусто. */
  message: string;
}

