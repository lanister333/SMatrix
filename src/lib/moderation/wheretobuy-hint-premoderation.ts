/**
 * Порядок кейсов — по нумерации заказчика: Кейс А (телефоны) →
 * Кейс Б (ярлыки). Оба ведут к БЛОКИРОВКЕ отправки с плашкой
 * перенаправления на форум «Товары и услуги ▸ Где купить».
 */
export function premoderateWhereToBuyHint(text: string): HintPremodVerdict {
  // Кейс А. Персональные данные физлиц: паттерны сотовых номеров
  // («+79…», «8-924…») — общий движок сайта (см. шапку файла).
  const phones = findPhoneNumbers(text);
  if (phones.length > 0) {
    return { verdict: "block", rule: "phones", hits: phones, message: WTB_HINT_PLAQUE_PHONES };
  }

  // Кейс Б. Эмоциональная перепалка/обвинения/оскорбления/субъективные
  // отзывы: шесть слов-маркеров заказчика.
  const labels = findEmotionalLabels(text);
  if (labels.length > 0) {
    return { verdict: "block", rule: "labels", hits: labels, message: WTB_HINT_PLAQUE_LABELS };
  }

  // Сухой географический факт (и вообще любой текст без запрещённого
  // контента) — ПРОПУСК НА ГЛАВНУЮ.
  return { verdict: "pass", rule: null, hits: [], message: "" };
}
