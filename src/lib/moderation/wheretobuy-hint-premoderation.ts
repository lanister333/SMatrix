/**
 * Префиксные основы: ловят все словоформы маркера. «Конторка» в значении
 * мебели (письменная конторка) тоже попадёт под маркер — заказчик назвал
 * слово маркером без оговорок, правило применяется 1-в-1. Основа «барыг»
 * добавлена ТЗ 2026-09-22 «сквозная логика» (список «барыги, хамы,
 * мошенники, уроды, вор, обдираловка»). Основа «спекулянт» добавлена
 * ТЗ 2026-09-23 (список части 4: «барыги, хамы, мошенники, уроды, вор,
 * обдираловка, спекулянты») — действует и в клиентском фильтре страниц
 * «Где купить»/«Где дешевле», и в первой линии подсказок.
 */
const LABEL_PREFIX_STEMS = ["барыг", "мошенник", "урод", "конторк", "обдираловк", "спекулянт"];

/**
 * Короткие маркеры — только точные словоформы: префикс «вор» ловил бы
 * «ворота/воронка/ворс», а «хам» — «хамса/хамелеон», поэтому они
 * перечисляются формами (как в первой линии отзывов «Рекомендую»).
 */
const LABEL_EXACT_WORDS = new Set([
  "вор", "вора", "вору", "вором", "воре", "воры", "воров", "ворам", "ворами", "ворах",
  "хам", "хама", "хаму", "хамы", "хамов", "хамам", "хамами", "хамах", "хаме",
  "хамка", "хамки", "хамке", "хамку", "хамкой",
]);

/** Разбивка на «слова» (только буквы) — как в первой линии отзывов. */
function labelWords(text: string): string[] {
  return text
    .toLowerCase()
    .replace(/ё/g, "е")
    .split(/[^а-яa-z]+/)
    .filter(Boolean);
}

/**
 * Поиск слов-маркеров Кейса Б. Экспортирована ТЗ 2026-09-22 «сквозная
 * логика»: клиентский фильтр формы переиспользует РОВНО этот же движок
 * (одинаковые решения на клиенте и на сервере — единый ИИ-фильтр).
 */
export function findEmotionalLabels(text: string): string[] {
  const hits: string[] = [];
  for (const raw of labelWords(text)) {
    if (LABEL_EXACT_WORDS.has(raw)) {
      hits.push(raw);
      continue;
    }
    if (LABEL_PREFIX_STEMS.some((stem) => raw.startsWith(stem))) {
      hits.push(raw);
    }
  }
  return hits;
}

