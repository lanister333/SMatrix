/**
 * Префиксные основы — ловят словоформы маркера. Основы «мошенник»/«урод»
 * добавлены ТЗ 2026-09-22 «сквозная логика» (список «барыги, хамы,
 * мошенники, уроды, вор, обдираловка»); прежние ценовые маркеры сохранены.
 */
const LABEL_PREFIX_STEMS = ["барыг", "оборзе", "обдираловк", "грабеж", "мошенник", "урод"];

/**
 * Короткие маркеры — только точные словоформы (см. шапку файла про «крутят»).
 * Семейства «вор»/«хам» добавлены ТЗ 2026-09-22 «сквозная логика» — те же
 * точные формы, что в первой линии «Где купить»: префикс «вор» ловил бы
 * «ворота/воронка/ворс», а «хам» — «хамса/хамелеон».
 */
const LABEL_EXACT_WORDS = new Set([
  "крутят",
  "вор", "вора", "вору", "вором", "воре", "воры", "воров", "ворам", "ворами", "ворах",
  "хам", "хама", "хаму", "хамы", "хамов", "хамам", "хамами", "хамах", "хаме",
  "хамка", "хамки", "хамке", "хамку", "хамкой",
]);

/** Многословные маркеры — фразы (регистр/ё/пробелы не важны; форма «сошли» 1-в-1). */
const LABEL_PHRASES: RegExp[] = [/с\s+ума\s+сошли/];

/** Разбивка на «слова» (только буквы) — как в остальных первых линиях. */
function labelWords(text: string): string[] {
  return text
    .toLowerCase()
    .replace(/ё/g, "е")
    .split(/[^а-яa-z]+/)
    .filter(Boolean);
}

/**
 * Поиск слов-маркеров Кейса Б. Экспортирована ТЗ 2026-09-22 «сквозная
 * логика»: клиентский фильтр формы переиспользует РОВНО этот же движок
 * (одинаковые решения на клиенте и на сервере — единый ИИ-фильтр).
 */
export function findEmotionalLabels(text: string): string[] {
  const hits: string[] = [];
  for (const raw of labelWords(text)) {
    if (LABEL_EXACT_WORDS.has(raw)) {
      hits.push(raw);
      continue;
    }
    if (LABEL_PREFIX_STEMS.some((stem) => raw.startsWith(stem))) {
      hits.push(raw);
    }
  }
  // Фразы ищем по нормализованному тексту («С ума сошли!», «с ума сошли»).
  const normalized = text.toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ");
  for (const re of LABEL_PHRASES) {
    const m = normalized.match(re);
    if (m) hits.push(m[0]);
  }
  return hits;
}

