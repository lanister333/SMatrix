/* Главная проверка первой линии быстрых цен «Где дешевле»             */
/* ------------------------------------------------------------------ */

/**
 * Порядок кейсов — по нумерации заказчика: Кейс А (телефоны) →
 * Кейс Б (ярлыки/критика ценообразования). Оба ведут к БЛОКИРОВКЕ
 * отправки с плашкой перенаправления на форум «Товары и услуги ▸ Цены».
 */
export function premoderateCheapHint(text: string): CheapHintPremodVerdict {
  // Кейс А. Персональные данные физлиц: паттерны сотовых номеров
  // («+79…», «8-914…») — общий движок сайта (см. шапку файла).
  const phones = findPhoneNumbers(text);
  if (phones.length > 0) {
    return { verdict: "block", rule: "phones", hits: phones, message: CHEAP_HINT_PLAQUE_PHONES };
  }

  // Кейс Б. Эмоциональная критика ценообразования, обвинения в спекуляции,
  // оскорбления: шесть маркеров заказчика.
  const labels = findEmotionalLabels(text);
  if (labels.length > 0) {
    return { verdict: "block", rule: "labels", hits: labels, message: CHEAP_HINT_PLAQUE_LABELS };
  }

  // Сухой факт стоимости (и вообще любой текст без запрещённого контента)
  // — ПРОПУСК НА ГЛАВНУЮ.
  return { verdict: "pass", rule: null, hits: [], message: "" };
}
