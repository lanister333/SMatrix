import { findPhoneNumbers } from "./premoderation";

export type CheapHintPremodVerdictKind = "pass" | "block";
/** Кейс А — телефоны, Кейс Б — эмоциональная критика ценообразования. */
export type CheapHintPremodRule = "phones" | "labels";

export interface CheapHintPremodVerdict {
  /** pass — пропуск на главную; block — блокировка с плашкой перенаправления. */
  verdict: CheapHintPremodVerdictKind;
  rule: CheapHintPremodRule | null;
  /** Сработавшие фрагменты (для логов/заметки модератора). */
  hits: string[];
  /** Текст строгой плашки Flat 2.0 (дословно заказчик). Для pass — пусто. */
  message: string;
}

