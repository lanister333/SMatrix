export const VOWELS = new Set(["а", "е", "ё", "и", "о", "у", "ы", "э", "ю", "я"]);

/** Согласный скелет слова (без гласных) — для ловли «мдак», «пздц». */
export function skeleton(word: string): string {
  return [...word]
    .filter((ch) => !VOWELS.has(ch) && ch !== "ь" && ch !== "ъ")
    .join("");
}
