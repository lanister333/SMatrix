/** Один сценарий: вопрос → кликабельный тестовый ввод → тема форума → URL. */
function ScenarioCard({ s }: { s: ScenarioTransfer }) {
  return (
    <article
      className="st-scenario"
      data-scenario={s.n}
      data-topic-slug={s.topicSlug}
      style={{ border: "1px solid #d4d4d8", background: "#fafafa", padding: "10px 12px" }}
    >
      <div className="st-head" data-scenario-head={s.n} style={{ fontSize: 13.5, fontWeight: 700, color: "#1E3A5F" }}>
        Сценарий {s.n} · {s.title}
      </div>

      {/* Вопрос на странице — дословно ТЗ. */}
      <div
        className="st-question"
        data-scenario-question={s.n}
        style={{ marginTop: 6, fontSize: 13.5, lineHeight: 1.5, color: "#1a1a1a" }}
      >
        <b>Вопрос:</b> «{s.question}».
      </div>

      {/*
        Тестовый ввод (Ошибка) — КЛИКАБЕЛЬНОЕ сообщение: href — ТОЧНЫЙ URL
        из ТЗ с уже закодированным prefilled_text (без искажений). Клик ведёт
        в тему форума рубрики, где текст предзаполняется в форму ответа.
      */}
      <a
        className="st-input"
        data-scenario-input={s.n}
        href={s.url}
        title="Клик — бесшовный перенос этого текста в тему форума (prefilled_text)"
        style={{ display: "block", marginTop: 7, fontSize: 13.5, lineHeight: 1.5, color: "#1E3A5F", textDecoration: "underline" }}
      >
        <b>Тестовый ввод (Ошибка):</b> «{s.input}»
      </a>

      {/* Привязка: тема форума + точный URL (структура ТЗ, оба шага на месте). */}
      <div className="st-meta" style={{ marginTop: 7, fontSize: 12.5, lineHeight: 1.55, color: "#57534e", wordBreak: "break-all" }}>
        <div data-scenario-topic={s.n}>
          <b>Тема форума:</b> {s.topicSlug}
        </div>
        <div>
          <b>URL:</b>{" "}
          <a className="st-url" data-scenario-url={s.n} href={s.url} style={{ color: "#1E3A5F" }}>
            {s.url}
          </a>
        </div>
        {/* Сценарий 7 (Cybex): поля «Автор» и «Дата» в том же компактном стиле. */}
        {s.author && (
          <div data-scenario-author={s.n}>
            <b>Автор:</b> {s.author}
          </div>
        )}
        {s.date && (
          <div data-scenario-date={s.n}>
            <b>Дата:</b> {s.date}
          </div>
        )}
      </div>

      {/*
        ТЗ «единый стиль 7 сценариев» + «переименование кнопки»: в КАЖДОЙ
        карточке — рабочая кнопка «Обсудить на форуме» (класс
        .wb-btn-forum.is-open из globals.css — бирюзовая, тот же шрифт/паддинг),
        ведущая в тему нужной рубрики по URL с prefilled_text (клик = переход
        в тему и предзаполнение формы ответа; текст не искажается).
      */}
      <div style={{ marginTop: 9 }}>
        <a
          className="wb-btn-forum is-open"
          data-scenario-forum={s.n}
          href={s.url}
          title="Открыть тему обсуждения на форуме — текст перенесётся в форму ответа (prefilled_text)"
          style={{ textDecoration: "none", display: "inline-block" }}
        >
          Обсудить на форуме
        </a>
      </div>
    </article>
  );
}

/**
 * Список тестовых сквозных сообщений внутри блока.
 *   block="wtb"   — блок «ГДЕ КУПИТЬ», сценарии 1-3;
 *   block="cheap" — блок «ГДЕ ДЕШЕВЛЕ», сценарии 4-6.
 */
export default function ScenarioTransfers({ block }: { block: "wtb" | "cheap" }) {
  const isWtb = block === "wtb";
  const scenarios = isWtb ? WTB_SCENARIO_TRANSFERS : CHEAP_SCENARIO_TRANSFERS;
  const blockTitle = isWtb ? "ГДЕ КУПИТЬ" : "ГДЕ ДЕШЕВЛЕ";
  const rubric = isWtb ? "Товары и услуги ▸ Где купить" : "Товары и услуги ▸ Цены";

  return (
    <section
      className="st-scenarios"
      aria-label={`Тестовые сквозные сообщения блока «${blockTitle}»`}
      {...(isWtb ? { "data-wtb-scenarios": "1" } : { "data-cheap-scenarios": "1" })}
      style={{ border: "1px solid #d3dce6", background: "#fff", padding: "12px 14px", margin: "14px 0 16px" }}
    >
      <div className="st-blocktitle" style={{ display: "flex", flexWrap: "wrap", alignItems: "baseline", gap: "4px 12px" }}>
        <span style={{ fontSize: 15, fontWeight: 800, letterSpacing: "0.02em", color: "#1E3A5F" }}>{blockTitle}</span>
        <span style={{ fontSize: 12.5, color: "#6b7280" }}>
          тестовые сквозные сообщения · рубрика форума: «{rubric}»
        </span>
      </div>
      <p className="st-desc" style={{ margin: "6px 0 10px", fontSize: 12.5, lineHeight: 1.5, color: "#475569" }}>
        Каждый сценарий — компактная карточка с рабочей кнопкой «Обсудить на форуме»: клик по кнопке или тестовому
        вводу бесшовно переносит текст в тему форума с параметром prefilled_text. Тестовые вводы помечены как «Ошибка»
        — нежелательный контент всё равно должен корректно переноситься на форум (проверка симулятора перехода).
      </p>
      <div className="st-list" style={{ display: "grid", gap: 10 }}>
        {scenarios.map((s) => (
          <ScenarioCard key={s.topicSlug} s={s} />
        ))}
      </div>
    </section>
  );
}
